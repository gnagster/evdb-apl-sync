'use strict';
const assert=require('node:assert/strict');
const T=require('../dashboard/tco.js');
const car={priceEur:30000,efficiencyWhKm:200,rangeKm:400,stopRangeKm:450};
const p={years:5,annualKm:10000,resale:15000,homePrice:.3,publicPrice:.6,homeSharePercent:100,lossPercent:0,insurance:500,tax:0,maintenance:200,tyres:100,thg:100};
let r=T.calculate(car,p);
assert.equal(r.annualEnergyKwh,2000);assert.equal(r.total,21500);assert.equal(r.monthly,21500/60);assert.equal(r.perKm,21500/50000);
assert.equal(T.calculate(car,{...p,lossPercent:20,homeSharePercent:50}).annualEnergyKwh,2500);
assert.equal(T.calculate(car,{...p,lossPercent:20,homeSharePercent:50}).items[1].value,5625);
assert.equal(T.calculate(car,{...p,homePrice:null,homeSharePercent:0}).total,24500);
assert.equal(T.calculate(car,{...p,insurance:null}).total,null);
assert(T.calculate(car,{...p,insurance:null}).missing.includes('Versicherung pro Jahr'));
assert.equal(T.calculate({...car,priceEur:null},p).total,null);
assert.equal(T.calculate({...car,efficiencyWhKm:null},p).total,null);
let f={...p,financed:true,downPayment:6000,interestPercent:0,loanMonths:60,balloon:6000};
r=T.calculate(car,f);assert.equal(r.monthlyPayment,300);assert.equal(r.remainingDebt,0);assert.equal(r.total,21500,'principal must not be counted twice');
r=T.calculate(car,{...f,years:2});assert.equal(r.remainingDebt,16800);assert.equal(r.interest,0);
r=T.calculate(car,{...f,interestPercent:6,balloon:0});assert(Math.abs(r.monthlyPayment-463.99)<.01);assert(Math.abs(r.interest-3839.23)<.1);
assert(Math.abs(T.calculate(car,{...f,interestPercent:6,years:2}).total-(T.calculate(car,{...p,years:2}).total+T.calculate(car,{...f,interestPercent:6,years:2}).interest))<.01);
for(const input of [{...p,financed:'false'},{...p,lossPercent:100},{...p,annualKm:0},{...p,insurance:-1},{...f,balloon:25000},{...f,downPayment:50000},{...f,loanMonths:2.5},{...p,years:NaN}]) assert.throws(()=>T.calculate(car,input));
console.log('PASS: TCO units, charging losses, missing inputs, cash purchase, zero interest, balloon and remaining debt');
